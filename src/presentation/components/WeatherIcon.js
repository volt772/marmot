function getWeatherIcon(weatherId) {
  const group = Math.floor(weatherId / 100);
  const remainder = weatherId % 100;

  switch (group) {
    case 2:
      return icons.Thunderstorm;
    case 3:
      return icons.Drizzle;
    case 5:
      return icons.Rain;
    case 6:
      return icons.Snow;
    case 7:
      return icons.Clouds;
    case 8:
      return remainder > 2 ? icons.Clouds : icons.Clear;
    default:
      return icons.Clear;
  }
}

export default function WeatherIcon({
  weatherId,
  size = 160,
  color = "#FFFFFF",
}) {
  const icon = getWeatherIcon(weatherId);

  return (
    <Svg width={size} height={size} viewBox={icon.viewBox}>
      {icon.paths.map((path, index) => (
        <Path
          key={index}
          d={path}
          fill={icon.outline ? "none" : color}
          fillRule={icon.fillRule ?? "nonzero"}
          stroke={icon.strokeWidth ? color : "none"}
          strokeWidth={icon.strokeWidth ?? 0}
          strokeLinecap={icon.outline ? "round" : "butt"}
          strokeLinejoin={icon.outline ? "round" : "miter"}
        />
      ))}
    </Svg>
  );
}
